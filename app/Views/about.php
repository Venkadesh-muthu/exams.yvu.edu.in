          </p>

          <p class="mb-3 lh-lg">
            c) Candidates for examinations whether Freshers or Repeaters shall pay the examination fees in
            the college where they have studied last and obtain the receipts.
          </p>

          <p class="mb-3 lh-lg">
            d) Cheques, Money Orders or Postal Orders shall not be accepted.
          </p>

          <p class="mb-4 lh-lg">
            f) Examination Fee, Marks Card Fee, Application Form Fee, and the Processing Fee collected by
            the college should be credited to the FEES AND REMUNERATION ACCOUNT of the Yogi Vemana
            University Funds. However, candidates appearing through the School of Distance Education and
            Continuing Education shall pay the examination fee as per instructions issued from time to time.
          </p>

          <!-- FILLING UP -->
          <h5 class="fw-bold mt-5 mb-3 border-start border-4 border-primary ps-3">
            Filling Up of Applications
          </h5>

          <p class="mb-3 lh-lg">
            a) Candidates whether Freshers or Repeaters have to send their Applications for examinations
            through the college where they studied last. Applications of candidates who studied one year in
            one affiliated/constituent college and the subsequent year in another college should be submitted
            through the college where they studied last.
          </p>

          <p class="mb-3 lh-lg">
            b) The candidate’s name must be the same as in the Admission Register maintained in the college.
            Change of name, if any, shall be supported by a copy of the University Order approving it.
          </p>

          <p class="mb-3 lh-lg">
            c) In case of wrong entry of name in Marks Memos, Consolidated Marks Memo, Provisional Certificate,
            Original Degree (Convocation), Migration etc., corrections will be issued only on receipt of Application
            through the College if the mistake occurred at Tabulation level. If the mistake is due to incorrect
            application entry by the candidate, prescribed fees must be paid.
          </p>

          <p class="mb-3 lh-lg">
            d) The Application Form is the same for Freshers and Repeaters. Only one Application must be
            submitted for all examinations. Candidates appearing for more than one year must give details separately.
          </p>

          <p class="mb-3 lh-lg">
            e) Register Number, year and month of passing the previous qualifying examination shall be checked
            with reference to office records.
          </p>

          <p class="mb-3 lh-lg">
            f) In case of failed candidates, previous Register Numbers, month and year of attempts,
            exemptions and benefits obtained shall be clearly indicated.
