            1.2 Examination Fees
          </h5>

          <p class="mb-3 lh-lg">
            a) Candidates appearing for an examination for the first time have to pay the full fees prescribed
            for the whole examination. There is no provision for the candidates to appear only for a part
            of an examination in their first appearance. It shall be carefully checked whether the prescribed
            fee for the examination including the Application Fee, fee for supplying the Marks Card and
            Processing Fee has been paid by the candidates.
          </p>

          <p class="mb-3 lh-lg">
            b) The rates of Examination Fee for various examinations and for different parts/divisions/papers
